// النسخة السابقة من هذا الملف كانت تحتوي على 14 "طبقة حماية" مثل:
// منع كليك يمين، منع النسخ/اللصق، منع تحديد النص، اكتشاف أدوات المطوّر،
// تعطيل eval/Function، محاولة "منع" PrintScreen... كل هذه إجراءات
// معروفة بأنها "أمان وهمي" (security theater):
//   • لا تمنع أي مهاجم جاد — يتم تجاوزها بسهولة (تعطيل JS، DevTools قبل
//     تحميل الصفحة، عرض المصدر عبر view-source:، إلخ)
//   • تُفسد تجربة الاستخدام وإمكانية الوصول (accessibility) لمستخدمين
//     شرعيين: قارئات الشاشة والتصفح بلوحة المفاتيح تعتمد أحياناً على
//     تحديد/نسخ النص، ومنعه يضر بالمستخدمين الحقيقيين لا المهاجمين
//   • تعطيل eval/Function قد يكسر مكتبات خارجية أو إضافات متصفح بصمت
//   • "منع" PrintScreen مستحيل تقنياً من المتصفح أصلاً (مفتاح على
//     مستوى نظام التشغيل)، والكود القديم كان بلا تأثير فعلي
//   • حقن نصوص تحذيرية في console لا يشكّل أي حماية
//
// كذلك: هذا موقع ثابت (static) بدون خادم/قاعدة بيانات، لذا فحماية
// SQL Injection غير ذات معنى هنا (لا يوجد استعلام قاعدة بيانات من
// الأساس). الخطر الحقيقي الوحيد كان XSS من بيانات المدن/ويكيبيديا
// المعروضة بدون تهريب — وقد تم إصلاح ذلك في 04-ui.js عبر escapeHtml().
//
// ما تبقّى أدناه هو الحماية الحقيقية الوحيدة الممكنة من جهة العميل:
// ============================================================

// ============================================================
// 1. منع تضمين الموقع داخل iframe من موقع آخر (Clickjacking)
// ============================================================
// هذا إجراء مشروع فعلاً، لكن يُفضَّل تطبيقه أيضاً (وبشكل أقوى) عبر
// ترويسة HTTP من الخادم: Content-Security-Policy: frame-ancestors 'none'
// أو X-Frame-Options: DENY — إجراء JS وحده يمكن تعطيله بسهولة نسبياً،
// لكنه أفضل من لا شيء لمن لا يتحكم بترويسات الخادم (مثل GitHub Pages).
(function preventClickjacking() {
    try {
        if (window.top !== window.self) {
            window.top.location = window.self.location;
        }
    } catch (e) {
        // الوصول لـ window.top قد يُرمى إذا كانت الصفحة المضمِّنة من نطاق مختلف
        // تماماً بقيود عزل صارمة؛ في هذه الحالة نُخفي المحتوى بدل الفشل بصمت
        document.documentElement.style.display = 'none';
    }
})();

console.log('✅ 06-security.js تم تحميله بنجاح (حماية حقيقية فقط: anti-clickjacking)');
